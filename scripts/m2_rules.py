#!/usr/bin/env python3
"""Pre-conversion rewrite rules for the M2 sync pipeline.

Kept in their own module because they are the part that will change most often: every new package
brought through the converter tends to surface another decompiler artefact ax3 will not parse.

Two hard constraints, both from the M2 architecture:

  * a rule is **guarded** -- it declares how many sites it expects, and a mismatch aborts the sync.
    A rewrite that silently stops matching is a behaviour change nobody reviewed.

    `expect` is a map of package to measured site count, because the count is a property of the
    package rather than of the rule. A package with no entry is reported as UNPINNED and the sync
    refuses to call itself clean: an unmeasured rule is exactly the silent rewrite this mechanism
    exists to prevent. (These were all `"any"` in the first draft, which made every guard a no-op
    -- the mechanism was there and disabled.)
  * a rule never encodes a fix that belongs in the converter. Where ax3 itself is wrong, patch ax3
    (as G1c did for `unescape`) so the fix travels with the tool rather than the corpus.

Every rule states what it repairs and why the original source looks that way. Most of these exist
because `habbo-client-clean` is decompiled: the AS3 is semantically what Flash ran, but its
formatting carries artefacts a hand-written codebase would not have.
"""
