#!/usr/bin/env python3
"""Generate packet-id/name lookup from authoritative HabboMessages.as."""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = Path(r"C:\habbo\client\habbo-client-clean\src\com\sulake\habbo\communication\HabboMessages.as")
OUTPUT = REPO / "generated/com/sulake/habbo/communication/GeneratedHabboMessageRegistry.hx"
EVIDENCE = REPO / "evidence/v3_message_registry.json"
PATTERN = re.compile(r"\b(INCOMING|OUTGOING)_PACKETS\[(\d+)\]\s*=\s*([A-Za-z_$][\w$]*);?")


def reverse_switch(name: str, rows: list[tuple[int, str]]) -> list[str]:
    """Emit the class-name -> packet-id lookup.

    A converted MessageEvent knows its own class but not its packet id; the connection seam has
    to turn one into the other to route a socket frame to it. Reversing the forward switch by
    scanning it at runtime would work but is 600 comparisons per registration, and this is the
    same data with the same guarantee that the ids are unique.
    """
    lines = [f"    public static function {name}(className:String):Int {{",
             "        return switch (className) {"]
    lines.extend(f'            case "{class_name}": {packet_id};' for packet_id, class_name in rows)
    lines.extend(["            default: -1;", "        };", "    }"])
    return lines


def switch(name: str, rows: list[tuple[int, str]]) -> list[str]:
    lines = [f"    public static function {name}(id:Int):Null<String> {{", "        return switch (id) {"]
    lines.extend(f'            case {packet_id}: "{class_name}";' for packet_id, class_name in rows)
    lines.extend(["            default: null;", "        };", "    }"])
    return lines


def main() -> int:
    data = SOURCE.read_bytes()
    text = data.decode("utf-8")
    incoming: list[tuple[int, str]] = []
    outgoing: list[tuple[int, str]] = []
    for direction, packet_id, class_name in PATTERN.findall(text):
        target = incoming if direction == "INCOMING" else outgoing
        target.append((int(packet_id), class_name))
    incoming.sort()
    outgoing.sort()
    if not incoming or not outgoing:
        raise SystemExit("no packet mappings parsed")
    if len({packet_id for packet_id, _ in incoming}) != len(incoming):
        raise SystemExit("duplicate incoming packet id")
    if len({packet_id for packet_id, _ in outgoing}) != len(outgoing):
        raise SystemExit("duplicate outgoing packet id")

    source_hash = hashlib.sha256(data).hexdigest()
    lines = [
        "package com.sulake.habbo.communication;",
        "",
        "/** Generated by scripts/generate-message-registry.py; do not edit. */",
        "class GeneratedHabboMessageRegistry {",
        f'    public static inline var SOURCE_SHA256:String = "{source_hash}";',
        f"    public static inline var INCOMING_COUNT:Int = {len(incoming)};",
        f"    public static inline var OUTGOING_COUNT:Int = {len(outgoing)};",
        "",
        *switch("incomingName", incoming),
        "",
        *reverse_switch("incomingId", incoming),
        "",
        *switch("outgoingName", outgoing),
        "",
        *reverse_switch("outgoingId", outgoing),
        "}",
        "",
    ]
    rendered = "\n".join(lines).encode("utf-8")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(rendered)
    evidence = {
        "gate": "V3-message-registry",
        "generator": "scripts/generate-message-registry.py",
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "source": str(SOURCE).replace("\\", "/"),
        "source_sha256": source_hash,
        "incoming": len(incoming),
        "outgoing": len(outgoing),
        "output": str(OUTPUT.relative_to(REPO)).replace("\\", "/"),
        "output_sha256": hashlib.sha256(rendered).hexdigest(),
    }
    EVIDENCE.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
    print(f"generated {len(incoming)} incoming + {len(outgoing)} outgoing packet mappings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
