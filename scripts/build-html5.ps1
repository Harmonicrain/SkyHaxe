[CmdletBinding()]
param(
    [switch] $Final,
    [switch] $SkipBootstrap
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot "..")).Path
if (-not $SkipBootstrap) {
    & (Join-Path $PSScriptRoot "bootstrap-toolchain.ps1")
}
. (Join-Path $PSScriptRoot "toolchain-env.ps1")

$openflArgs = @("run", "openfl", "build", "html5")
$openflArgs += if ($Final) { "-final" } else { "-debug" }

Push-Location $repoRoot
try {
    & python "scripts/generate-message-registry.py"
    if ($LASTEXITCODE -ne 0) {
        throw "Message registry generation failed with exit code $LASTEXITCODE"
    }
    # Message parsers are no longer generated by a bespoke script: ax3 converts all 559 through
    # the ordinary sync pipeline (scripts/sync.py --package
    # com/sulake/habbo/communication/messages/parser). See evidence/v3c_parser_pipeline.json.
    # Haxe writes warnings to stderr, and under Windows PowerShell 5.1 with
    # $ErrorActionPreference = "Stop" any stderr line from a native executable becomes a
    # terminating NativeCommandError -- a deprecation warning would fail an otherwise clean build.
    # The exit code is the real signal, so relax the preference across the call and keep checking
    # $LASTEXITCODE. Same fix as scripts/build-m2-converter.ps1.
    $previousPreference = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try { & haxelib @openflArgs }
    finally { $ErrorActionPreference = $previousPreference }
    if ($LASTEXITCODE -ne 0) {
        throw "OpenFL HTML5 build failed with exit code $LASTEXITCODE"
    }

    $index = Join-Path $repoRoot "build\html5\bin\index.html"
    if (-not (Test-Path -LiteralPath $index -PathType Leaf)) {
        throw "OpenFL reported success but did not produce $index"
    }
    Write-Host "Built $index"
}
finally {
    Pop-Location
}
