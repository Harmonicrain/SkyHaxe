#!/usr/bin/env python3
"""Name every generated and isolated-candidate type in the compile-only gate."""
from pathlib import Path
import argparse
import json
import re

REPO = Path(__file__).resolve().parents[1]
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", action="append", default=[])
    parser.add_argument("--main", default="AllGeneratedCompileMain")
    parser.add_argument("--output", default="test/AllGeneratedCompileMain.hx")
    parser.add_argument("--manifest", default="evidence/compile_all_inventory.json")
    parser.add_argument("--compile-command",
                        default="haxelib run openfl build project.compile-all.xml html5 -debug")
    args = parser.parse_args()
    source_roots = args.source_root or [".toolchain/v31/generated"]
    owners, skipped = {}, []
    for root_name in source_roots:
        root = REPO / root_name
        if not root.exists():
            continue
        for path in sorted(root.rglob("*.hx")):
            if path.name == "import.hx":
                continue
            text = path.read_text(encoding="utf-8-sig")
            if not re.search(r"\b(?:class|interface|abstract|enum|typedef)\s+" +
                             re.escape(path.stem) + r"\b", text):
                skipped.append(path.relative_to(REPO).as_posix())
                continue
            identity = path.relative_to(root).with_suffix("").as_posix().replace("/", ".")
            owners.setdefault(identity, []).append(path.relative_to(REPO).as_posix())
    identities = sorted(owners)
    output = REPO / args.output
    output.write_text("/** Generated by scripts/generate-compile-all.py. Compile-only, never runtime. */\n"
                      f"class {args.main} {{\n" +
                      "\n".join(f"    static var type{index}:{identity};"
                                for index, identity in enumerate(identities)) +
                      "\n    public static function main():Void {}\n}\n", encoding="utf-8")
    duplicates = {identity: paths for identity, paths in owners.items() if len(paths) > 1}
    manifest = {"source_roots": source_roots, "identities": identities, "types": len(identities),
                "owners": owners, "duplicate_identities": duplicates,
                "unrecognized_modules": skipped,
                "compile_command": args.compile_command,
                "note": "The root forces every identity in the selected isolated candidate to type-check. Deliberately absent identities resolve only from declared source/runtime boundaries. Compilation is not proof of runtime wiring."}
    (REPO / args.manifest).write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Compile root names {len(identities)} types across {len(source_roots)} roots; "
          f"duplicate identities: {len(duplicates)}; unrecognized modules: {skipped}")
    return 1 if skipped else 0


if __name__ == "__main__":
    raise SystemExit(main())
